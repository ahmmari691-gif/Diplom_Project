TYPE_NAMES = {'auto', 'other', *SECTORS}

def experience(b):
    kind = getattr(b, 'business_type', 'auto')
    if kind == 'auto':
        # Specific catalog/description signals take precedence over a broad category.
        category = b.category.lower()
        explicit = [('education', r'обуч|репетитор|образова|языковая школа'),
                    ('beauty', r'красота|маникюр|парикмах|косметолог'),
                    ('flowers', r'цветы|растени|флорист'),
                    ('food', r'кондитер|выпеч|домашняя еда|кулинари'),
                    ('craft', r'керамик|гончар|пошив|шить|вязани')]
        category_kind = next((name for name, pattern in explicit if re.search(pattern, category)), None)
        text = ' '.join([b.category, b.description, *b.products.values_list('name', flat=True)]).lower()
        rules = [('education', r'обуч|учеб|урок|англий|англиск|репетитор|заняти|преподав|подготовк.{0,30}(дет|школ|экзам)|курс'),
                 ('beauty', r'маникюр|педикюр|бров|ресниц|стриж|парикмах|визаж|макияж|косметолог|красота'),
                 ('flowers', r'букет|флорист|цветоч|растени|цветы'),
                 ('food', r'кондитер|бенто|торт|капкейк|десерт|выпеч|пирог|печень|домашняя еда|кулинари|меню'),
                 ('craft', r'керамик|гончар|вязани|вязаны|шить|пошив|свеч|ручной работы|handmade|украшени'),
                 ('services', r'услуг|ремонт|уборк|фотограф|дизайн|консультац'),
                 ('retail', r'магазин|торговл|продажа товаров')]
        kind = category_kind or next((name for name, pattern in rules if re.search(pattern, text)), 'other')
    result = {**BASE, **SECTORS.get(kind, {}), 'kind': kind}
    if result['isService'] and kind != 'education':
        result['statuses'] = {'new': 'Новая заявка', 'working': 'В работе', 'ready': 'Запись подтверждена', 'done': 'Услуга оказана', 'cancelled': 'Отменена'}
        result.update(readyAction='Подтвердить запись', doneAction='Услуга оказана', readyMetric='Записи подтверждены')
    return result
